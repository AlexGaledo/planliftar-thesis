#!/usr/bin/env python3
"""Generate the PWA icon set.

Committed as PNGs so the server needs no build step, but generated by script
so they are reproducible and easy to restyle. Chrome's install criteria want
a 192 and a 512; the maskable variants carry the 20% safe-area padding Android
needs before it crops the icon to whatever shape the launcher uses.

    python deliverables/livemap/make_icons.py
"""
import os

from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "icons")

# Monochrome, matching the black-and-white the map and AR view switched to.
BG = (255, 255, 255)
FG = (17, 17, 17)


def draw_plan(size, pad_frac):
    """A floorplan glyph: outer walls with a doorway gap, one interior wall.

    The gap is the point - it is the thing this project is about, and it reads
    at 48 px where a more detailed plan would turn to mush.
    """
    img = Image.new("RGB", (size, size), BG)
    d = ImageDraw.Draw(img)
    pad = int(size * pad_frac)
    w = max(2, int(size * 0.075))          # wall thickness, scales with icon
    x0, y0, x1, y1 = pad, pad, size - pad, size - pad

    # outer walls, drawn as four bars so one can be left short for the doorway
    d.rectangle([x0, y0, x1, y0 + w], fill=FG)                 # top
    d.rectangle([x0, y1 - w, x1, y1], fill=FG)                 # bottom
    d.rectangle([x0, y0, x0 + w, y1], fill=FG)                 # left
    door = int((y1 - y0) * 0.30)                               # doorway height
    d.rectangle([x1 - w, y0, x1, y1 - door], fill=FG)          # right, stops short

    # one interior wall, also stopping short - a second opening
    mx = x0 + int((x1 - x0) * 0.55)
    d.rectangle([mx, y0 + w, mx + w, y1 - door - int(size * 0.06)], fill=FG)
    return img


def main():
    os.makedirs(OUT, exist_ok=True)
    made = []
    for size in (192, 512):
        p = os.path.join(OUT, "icon-%d.png" % size)
        draw_plan(size, 0.16).save(p, "PNG", optimize=True)
        made.append(p)
        # Maskable: same glyph, more padding, because Android crops to a
        # circle/squircle and anything in the outer 10% can be cut off.
        p = os.path.join(OUT, "maskable-%d.png" % size)
        draw_plan(size, 0.28).save(p, "PNG", optimize=True)
        made.append(p)
    for p in made:
        print("wrote %s (%d bytes)" % (os.path.relpath(p, HERE), os.path.getsize(p)))


if __name__ == "__main__":
    main()
